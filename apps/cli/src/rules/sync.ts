import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import type { components } from '@onebrain/sdk';
import { type ClientName, clients } from '../agents/index.ts';
import { type CliClient, CliError, type Io, unwrap } from '../client.ts';

export const RULES_START = '<!-- onebrain:rules:start -->';
export const RULES_END = '<!-- onebrain:rules:end -->';

/**
 * The files rules sync keeps, at the repository root. A missing one is created only when its
 * client is set up on this machine (detect, the check onebrain init uses). header starts a file
 * this command creates. Cursor project rules are .mdc files with frontmatter; alwaysApply: true
 * applies the rule to every chat (cursor.com/docs/context/rules).
 */
export const RULE_TARGETS: { file: string; client: ClientName; header: string }[] = [
  { file: 'AGENTS.md', client: 'codex', header: '' },
  { file: 'CLAUDE.md', client: 'claude-code', header: '' },
  {
    file: '.cursor/rules/onebrain.mdc',
    client: 'cursor',
    header: '---\ndescription: Team rules synced from One Brain\nalwaysApply: true\n---\n\n',
  },
];

export type Rule = { path: string; body: string };
export type RulesResult = {
  folder: string;
  rules: number;
  created: string[];
  updated: string[];
  unchanged: string[];
  failed: string[];
};

type TreeNode = NonNullable<components['schemas']['Node']>;
const bare = (line: string) => line.replace(/\r$/, '');
const isMarker = (line: string) => bare(line) === RULES_START || bare(line) === RULES_END;

/** The nearest folder at or above cwd that holds .git (a folder, or a file in a worktree). */
export function findRepoRoot(cwd: string): string | null {
  for (let dir = resolve(cwd); ; dir = dirname(dir)) {
    if (existsSync(join(dir, '.git'))) return dir;
    if (dirname(dir) === dir) return null;
  }
}

/** The .md files directly in a shared folder that the caller can read, by name. */
export async function readRules({ api, workspace }: CliClient, folder: string): Promise<Rule[]> {
  const listed = await api.GET('/v1/workspaces/{workspace}/tree', {
    params: { path: { workspace }, query: { path: folder } },
  });
  if (listed.response.status === 404) {
    throw new CliError(`No folder ${folder} in workspace ${workspace}, or you cannot see it.`);
  }
  const tree = unwrap(listed);
  if (tree.node?.kind !== 'folder') throw new CliError(`${folder} is not a folder.`, 2);
  const files = tree.children
    .filter((node): node is TreeNode => node?.kind === 'file' && node.name.endsWith('.md'))
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const rules: Rule[] = [];
  for (const node of files) {
    const file = unwrap(
      await api.GET('/v1/workspaces/{workspace}/files', {
        params: { path: { workspace }, query: { path: node.path } },
      }),
    );
    rules.push({ path: file.path, body: file.body });
  }
  return rules;
}

/** The managed block: the markers, the generated note, then each rule under a line naming its path. */
export function renderBlock(rules: Rule[], folder: string, workspace: string): string {
  const lines = [
    RULES_START,
    `<!-- Generated by onebrain rules sync from the One Brain folder ${folder} (workspace ${workspace}). Change the rules there, then run onebrain rules sync again: edits inside this block are overwritten. -->`,
  ];
  for (const rule of rules) {
    if (rule.body.split('\n').some(isMarker)) {
      throw new CliError(
        `${rule.path} holds a onebrain rules marker line. Remove it in One Brain, then sync again.`,
      );
    }
    lines.push('', `<!-- ${rule.path} -->`, rule.body.trim());
  }
  lines.push(RULES_END);
  return lines.join('\n');
}

/**
 * The file's text with its block replaced, or with the block appended after a blank line when it
 * has none. Every byte outside the block stays as it was. existing null: a new file, header first.
 * Returns null when the markers are broken (not exactly one start line with one end line after it).
 */
export function applyBlock(existing: string | null, block: string, header: string): string | null {
  if (existing === null) return `${header}${block}\n`;
  const lines = existing.split('\n');
  const starts = lines.flatMap((line, i) => (bare(line) === RULES_START ? [i] : []));
  const ends = lines.flatMap((line, i) => (bare(line) === RULES_END ? [i] : []));
  if (starts.length === 0 && ends.length === 0) {
    const gap = existing === '' ? '' : existing.endsWith('\n') ? '\n' : '\n\n';
    return `${existing}${gap}${block}\n`;
  }
  const start = starts[0];
  const end = ends[0];
  if (
    starts.length !== 1 ||
    ends.length !== 1 ||
    start === undefined ||
    end === undefined ||
    end < start
  ) {
    return null;
  }
  lines.splice(start, end - start + 1, ...block.split('\n'));
  return lines.join('\n');
}

/** Writes the rules of one shared folder into each target file at the repository root. */
export async function syncRules(
  io: Io,
  options: { folder: string; check: boolean },
): Promise<RulesResult> {
  const folder = options.folder.replace(/^[\s/]+|[\s/]+$/g, '');
  if (!folder || folder === 'me' || folder.startsWith('me/')) {
    throw new CliError(
      'Rules come from one shared folder: not the root, and nothing under me/.',
      2,
    );
  }
  const root = findRepoRoot(io.cwd);
  if (!root) throw new CliError('Run onebrain rules sync inside a git repository.', 2);
  const client = await io.client();
  const rules = await readRules(client, folder);
  const block = renderBlock(rules, folder, client.workspace);
  const result: RulesResult = {
    folder,
    rules: rules.length,
    created: [],
    updated: [],
    unchanged: [],
    failed: [],
  };
  for (const target of RULE_TARGETS) {
    const path = join(root, target.file);
    const existing = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (existing === null && !clients[target.client].detect(io.home)) continue;
    const next = applyBlock(existing, block, target.header);
    if (next === null) {
      io.stderr(
        `skipped ${target.file}: its onebrain rules markers are broken. Keep one start line and one end line after it, or remove both.\n`,
      );
      result.failed.push(target.file);
      continue;
    }
    if (next === existing) {
      result.unchanged.push(target.file);
      continue;
    }
    if (!options.check) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, next);
    }
    (existing === null ? result.created : result.updated).push(target.file);
  }
  return result;
}
