import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  statSync,
  utimesSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { describe, expect, it } from 'vitest';
import type { OneBrainClient } from '../src/client.ts';
import rules from '../src/commands/rules.ts';
import { findRepoRoot, RULES_END, RULES_START } from '../src/rules/sync.ts';
import { fakeApi, testIo } from './helpers.ts';

const W = '/v1/workspaces/kenso';
const at = '2026-11-13T00:00:00.000Z';
const RULES: Record<string, string> = {
  'rules/testing.md': '# Testing\nRun scoped tests only.\n',
  'rules/style.md': '# Style\nUse simple dashes.\n',
};
const node = (kind: 'folder' | 'file' | 'skill', path: string) => ({
  id: `id-${path}`,
  kind,
  name: path.split('/').pop() ?? path,
  path,
  visibility: 'workspace',
  access: null,
  writePolicy: null,
  currentVersion: kind === 'file' ? 1 : null,
  updatedAt: at,
});
const CHILDREN = [
  node('folder', 'rules/old'),
  node('skill', 'rules/reply'),
  node('file', 'rules/testing.md'),
  node('file', 'rules/notes.txt'),
  node('file', 'rules/style.md'),
];

/** A brain whose rules folder holds two Markdown files, a text file, a subfolder and a skill. */
function brain(bodies: Record<string, string> = RULES) {
  return fakeApi({
    [`GET ${W}/tree`]: (call) =>
      call.query.get('path') === 'rules'
        ? { body: { node: node('folder', 'rules'), children: CHILDREN } }
        : { status: 404, body: { error: { code: 'not_found', message: 'Not found' } } },
    [`GET ${W}/files`]: (call) => {
      const path = call.query.get('path') ?? '';
      return {
        body: {
          id: `id-${path}`,
          path,
          version: 1,
          body: bodies[path],
          visibility: 'workspace',
          changeKind: 'create',
          author: { id: 'p1', displayName: 'A' },
          onBehalfOf: null,
          updatedAt: at,
        },
      };
    },
  });
}

/** A git repository in a temp folder holding the given files. */
function repo(files: Record<string, string> = {}): string {
  const dir = mkdtempSync(join(tmpdir(), 'onebrain-rules-'));
  mkdirSync(join(dir, '.git'));
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true });
    writeFileSync(join(dir, name), text);
  }
  return dir;
}

/** Runs onebrain rules with cwd in the repository. clients: folders that set an AI client up in home. */
async function run(
  args: string[],
  options: { cwd: string; api?: OneBrainClient; clients?: string[] },
) {
  const t = testIo({ api: options.api ?? brain().api });
  for (const folder of options.clients ?? []) mkdirSync(join(t.home, folder));
  const code = await rules.run(args, { ...t.io, cwd: options.cwd });
  return { code, stdout: t.stdout(), stderr: t.stderr() };
}
const read = (dir: string, file: string) => readFileSync(join(dir, file), 'utf8');

describe('rules sync', () => {
  it('appends the rules, by name, to the files that exist and keeps the rest of each file', async () => {
    const dir = repo({
      'AGENTS.md': '# Our agents\nKeep this.\n',
      'CLAUDE.md': 'No newline at the end',
    });
    mkdirSync(join(dir, 'src/deep'), { recursive: true });
    const { api, calls } = brain();
    const out = await run(['sync'], { cwd: join(dir, 'src/deep'), api });
    expect(out.code).toBe(0);
    const agents = read(dir, 'AGENTS.md');
    expect(
      agents.startsWith(
        `# Our agents\nKeep this.\n\n${RULES_START}\n<!-- Generated by onebrain rules sync from the One Brain folder rules `,
      ),
    ).toBe(true);
    expect(
      agents.endsWith(
        `<!-- rules/style.md -->\n# Style\nUse simple dashes.\n\n<!-- rules/testing.md -->\n# Testing\nRun scoped tests only.\n${RULES_END}\n`,
      ),
    ).toBe(true);
    expect(read(dir, 'CLAUDE.md').startsWith(`No newline at the end\n\n${RULES_START}\n`)).toBe(
      true,
    );
    expect(existsSync(join(dir, '.cursor'))).toBe(false);
    const reads = calls.filter((c) => c.path === `${W}/files`).map((c) => c.query.get('path'));
    expect(reads).toEqual(['rules/style.md', 'rules/testing.md']);
    expect(out.stdout).toContain('updated AGENTS.md\nupdated CLAUDE.md\n');
    expect(out.stdout).toContain('Synced 2 rules from rules: 0 created, 2 updated, 0 unchanged.');
  });

  it('replaces only its block on the next run, and writes nothing when nothing changed', async () => {
    const dir = repo({ 'AGENTS.md': '# Ours\n' });
    await run(['sync'], { cwd: dir });
    writeFileSync(join(dir, 'AGENTS.md'), `Before\n${read(dir, 'AGENTS.md')}After\n`);
    const changed = { ...RULES, 'rules/style.md': '# Style\nUse plain words.\n' };
    expect((await run(['sync'], { cwd: dir, api: brain(changed).api })).code).toBe(0);
    const text = read(dir, 'AGENTS.md');
    expect(text.startsWith(`Before\n# Ours\n\n${RULES_START}\n`)).toBe(true);
    expect(text.endsWith(`${RULES_END}\nAfter\n`)).toBe(true);
    expect(text).toContain('Use plain words.');
    expect(text).not.toContain('Use simple dashes.');
    const old = new Date('2020-01-01T00:00:00.000Z');
    utimesSync(join(dir, 'AGENTS.md'), old, old);
    const again = await run(['sync'], { cwd: dir, api: brain(changed).api });
    expect(again.stdout).toContain('0 created, 0 updated, 1 unchanged');
    expect(statSync(join(dir, 'AGENTS.md')).mtime.getTime()).toBe(old.getTime());
  });

  it('creates a missing file only for an AI client set up on this machine', async () => {
    const dir = repo();
    const claude = await run(['sync'], { cwd: dir, clients: ['.claude'] });
    expect(claude.stdout).toContain('created CLAUDE.md');
    expect(read(dir, 'CLAUDE.md').startsWith(`${RULES_START}\n`)).toBe(true);
    expect(existsSync(join(dir, 'AGENTS.md'))).toBe(false);
    expect(existsSync(join(dir, '.cursor/rules/onebrain.mdc'))).toBe(false);
    await run(['sync'], { cwd: dir, clients: ['.cursor'] });
    const mdc = read(dir, '.cursor/rules/onebrain.mdc');
    expect(mdc.startsWith('---\n')).toBe(true);
    expect(mdc).toContain('alwaysApply: true');
    expect(mdc).toContain(`${RULES_START}\n`);
    const none = await run(['sync'], { cwd: repo() });
    expect(none.code).toBe(0);
    expect(none.stderr).toContain('onebrain init');
  });

  it('--check writes nothing, exits 1 while a file is out of step and 0 once it is in step', async () => {
    const dir = repo({ 'AGENTS.md': '# Ours\n' });
    const before = await run(['sync', '--check'], { cwd: dir });
    expect(before.code).toBe(1);
    expect(before.stdout).toContain('out of step: AGENTS.md');
    expect(read(dir, 'AGENTS.md')).toBe('# Ours\n');
    await run(['sync'], { cwd: dir });
    const after = await run(['sync', '--check'], { cwd: dir });
    expect(after.code).toBe(0);
    expect(after.stdout).toContain('In step');
  });

  it('never reads rules from me/ or the root', async () => {
    const dir = repo({ 'AGENTS.md': '# Ours\n' });
    for (const folder of ['me', 'me/rules', '/me/rules/', '/', ' ']) {
      const { api, calls } = brain();
      await expect(run(['sync', '--folder', folder], { cwd: dir, api })).rejects.toMatchObject({
        exitCode: 2,
      });
      expect(calls).toEqual([]);
    }
    expect(read(dir, 'AGENTS.md')).toBe('# Ours\n');
  });

  it('writes nothing when the folder is missing or hidden, or a rule holds a marker line', async () => {
    const dir = repo({ 'AGENTS.md': '# Ours\n' });
    await expect(run(['sync', '--folder', 'hidden'], { cwd: dir })).rejects.toThrow(
      /No folder hidden/,
    );
    const marked = { ...RULES, 'rules/style.md': `ok\n${RULES_END}\n` };
    await expect(run(['sync'], { cwd: dir, api: brain(marked).api })).rejects.toThrow(/marker/);
    expect(read(dir, 'AGENTS.md')).toBe('# Ours\n');
  });

  it('leaves a file with broken markers alone, syncs the others and exits 1', async () => {
    const broken = `# Ours\n${RULES_START}\nhalf a block\n`;
    const dir = repo({ 'AGENTS.md': broken, 'CLAUDE.md': '# Claude\n' });
    const out = await run(['sync'], { cwd: dir });
    expect(out.code).toBe(1);
    expect(out.stderr).toContain('skipped AGENTS.md');
    expect(read(dir, 'AGENTS.md')).toBe(broken);
    expect(read(dir, 'CLAUDE.md')).toContain(RULES_START);
  });

  // Skipped on a machine whose temp folder sits inside a git repository.
  it.skipIf(findRepoRoot(tmpdir()) !== null)(
    'refuses to run outside a git repository',
    async () => {
      const dir = mkdtempSync(join(tmpdir(), 'onebrain-norepo-'));
      await expect(run(['sync'], { cwd: dir })).rejects.toMatchObject({ exitCode: 2 });
    },
  );
});
